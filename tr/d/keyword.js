  function generate(opts) {
    opts = opts || {};
    var maxEmoji = typeof opts.maxEmoji === 'number' ? opts.maxEmoji : 3;

    var tail = pick(TAILS);

    var preCount = randInt(0, maxEmoji);
    var sufCount = randInt(0, maxEmoji);
    var pre = toEmoji(pickN(EMOJI_POOL, preCount));
    var suf = toEmoji(pickN(EMOJI_POOL, sufCount));

    var copyWord = (opts.word && isPureCJK(opts.word)) ? opts.word : pickCopyWord();
    var searchTag = pick(CORE_WORDS);

    var code;
    if (DOMAIN_HEAD && DOMAIN_TAIL) {
      code = DOMAIN_HEAD + '.' + copyWord + DOMAIN_TAIL;
    } else {
      code = DOMAIN_HEAD + '.' + copyWord + randomCase(pick(LATIN_SUFFIX));
    }

    var text = pre + code + '   ' + copyWord + tail + suf;

    return {
      text: text,          // 完整文案
      keyword: searchTag,  // ★ 第二步搜索词（带 #，与文案无关）
      copyWord: copyWord,  // 第一步文案里那个词
      code: code,          // 编码段原文
      domain: SHORT_DOMAIN || code,  // 删掉中文词后的可访问地址
      tail: tail
    };
  }

