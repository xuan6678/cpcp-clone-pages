  function randInt(min, max) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
  }

  function pick(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
  }

  function pickN(arr, n) {
    var out = [];
    for (var i = 0; i < n; i++) out.push(pick(arr));
    return out;
  }

  function randomCase(s) {
    var out = '';
    for (var i = 0; i < s.length; i++) {
      out += Math.random() < 0.5 ? s[i].toUpperCase() : s[i].toLowerCase();
    }
    return out;
  }

  function toEmoji(names) {
    var out = '';
    for (var i = 0; i < names.length; i++) out += '[' + names[i] + ']';
    return out;
  }

